import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'
import ts from 'typescript'
import ExcelJS from 'exceljs'

const require = createRequire(import.meta.url)
const compile = path => ts.transpileModule(readFileSync(new URL(path, import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText
const dataUrl = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
const routeUrl = dataUrl(compile('../src/views/Leaderboard/everestRoutes.ts'))
const rosterUrl = dataUrl(compile('../src/views/Leaderboard/leaderboardData.ts').replace(/from ['"]\.\/everestRoutes['"]/, `from '${routeUrl}'`))
const excelUrl = dataUrl(compile('../src/views/Leaderboard/leaderboardExcel.ts').replace(/from ['"]\.\/leaderboardData['"]/, `from '${rosterUrl}'`).replace(/import\(['"]exceljs['"]\)/g, `import('${pathToFileURL(require.resolve('exceljs')).href}')`).replace(/import\(['"]jszip['"]\)/g, `import('${pathToFileURL(require.resolve('jszip')).href}')`))
const { createClassroom, parseDelimited, recognizeRows, importCandidates, loadClassrooms, classStatistics, clearClassroomRoster, restoreClassroomRoster, bindStudentRole, defaultAvatarFor, studentIdentity, studentLabel, updateStudentNameTag, CLASSROOM_STORAGE_KEY } = await import(rosterUrl)
const { exportClassrooms, readExcelCandidates, normalizeExcelArchive, createImportTemplate } = await import(excelUrl)
const initial = createClassroom('高一1班')
const store = { version: 2, activeClassId: initial.id, classes: [initial] }
const rows = parseDelimited('班级,姓名,分数,性别\r\n高一1班,"张,三",7,男\r\n高一2班,张三,0,女\r\n高一1班,李四,,女\r\n高一1班,错误,-2,男')
const candidates = recognizeRows(rows, initial.name)
assert.equal(candidates.length, 4)
assert.equal(candidates[0].name, '张,三')
assert.equal(candidates[2].score, 0)
assert.equal(candidates[3].include, false)
assert.equal(candidates[2].gender, '女')
const missingGender = recognizeRows([['姓名', '性别'], ['缺性别', '']], initial.name)[0]
assert.equal(missingGender.error, '请选择性别')
assert.equal(importCandidates(store, [missingGender]).added, 0)
assert.equal(recognizeRows(parseDelimited('小红 女 3\n高二1班 小明 男 0'), initial.name)[0].gender, '女')
assert.equal(recognizeRows(parseDelimited('小红 女 3\n高二1班 小明 男 0'), initial.name)[1].className, '高二1班')
const imported = importCandidates(store, candidates)
assert.equal(imported.added, 3)
assert.equal(imported.store.classes.length, 2)
assert.equal(store.classes[0].students.length, 0, 'import preview must not mutate existing data')
const slots = imported.store.classes[0].students.map(student => student.routeSlot)
assert.equal(new Set(slots).size, slots.length)
assert.equal(classStatistics(imported.store.classes[0]).total, 7)
const duplicate = importCandidates(imported.store, candidates)
assert.equal(duplicate.added, 0)
assert.equal(duplicate.skipped, 3)
const candidate = { ...candidates[0], score: 12 }
assert.equal(importCandidates(imported.store, [candidate]).store.classes[0].students[0].score, 7, 'duplicates preserve scores by default')
assert.equal(importCandidates(imported.store, [candidate], true).store.classes[0].students[0].score, 12)
const serialized = JSON.stringify(imported.store)
const restored = loadClassrooms({ getItem: key => key === CLASSROOM_STORAGE_KEY ? serialized : null }, [], 50)
assert.deepEqual(restored.classes.map(group => group.students.map(student => student.routeSlot)), imported.store.classes.map(group => group.students.map(student => student.routeSlot)))
const cleared = clearClassroomRoster(imported.store, initial.id)
assert.equal(cleared.store.classes[0].students.length, 0)
assert.equal(classStatistics(cleared.store.classes[0]).total, 0)
assert.equal(cleared.store.classes[0].segments, initial.segments)
assert.deepEqual(cleared.store.classes[1], imported.store.classes[1], 'clearing one class must preserve other classes')
const persistedEmpty = JSON.stringify(cleared.store)
assert.equal(loadClassrooms({ getItem: () => persistedEmpty }, [], 50).classes[0].students.length, 0, 'reload must not replace an empty class with sample students')
assert.deepEqual(restoreClassroomRoster(cleared.store, cleared.snapshot).classes[0].students, imported.store.classes[0].students)
const newlyAdded = importCandidates(cleared.store, [{ ...candidates[0], name: '新队员', score: 0 }]).store
const recovered = restoreClassroomRoster(newlyAdded, cleared.snapshot).classes[0].students
assert.equal(recovered.length, imported.store.classes[0].students.length + 1)
assert.equal(new Set(recovered.map(student => student.routeSlot)).size, recovered.length, 'undo after new additions must keep distinct routes')
const avatar = `data:image/png;base64,${readFileSync(new URL('../public/images/leaderboard/default-avatar.png', import.meta.url)).toString('base64')}`
const bound = bindStudentRole(imported.store, initial.id, imported.store.classes[0].students[0].id, '男', avatar)
assert.throws(() => bindStudentRole(bound, initial.id, bound.classes[0].students[1].id, '女', avatar), /同班不能重复/)
assert.doesNotThrow(() => bindStudentRole(bound, bound.classes[1].id, bound.classes[1].students[0].id, '女', avatar), 'other classes may reuse the same role')
assert.throws(() => importCandidates(bound, [{ ...candidates[2], name: '另一人', avatar }]), /同班不能重复/)
const unbound = bindStudentRole(bound, initial.id, bound.classes[0].students[0].id, '女')
assert.equal(unbound.classes[0].students[0].avatar, undefined)
assert.equal(defaultAvatarFor(unbound.classes[0].students[0].gender), '/images/leaderboard/default-girl.png')
assert.equal(bound.classes[0].students[0].avatar, avatar, 'binding operations must not mutate old stores')
const boundReload = loadClassrooms({ getItem: () => JSON.stringify(bound) }, [], 50)
assert.equal(boundReload.classes[0].students[0].avatar, avatar)
assert.equal(boundReload.classes[0].students[1].gender, '女')
assert.throws(() => importCandidates(store, [{ ...candidates[0], gender: '', error: undefined }]), /性别/)
const genderlessSaved = JSON.parse(serialized)
delete genderlessSaved.classes[0].students[0].gender
const migratedGender = loadClassrooms({ getItem: () => JSON.stringify(genderlessSaved) }, [], 50)
assert.equal(migratedGender.classes[0].students[0].gender, '男')
assert.equal(migratedGender.classes[0].students[0].score, 7, 'gender migration must preserve scores')
assert.equal(migratedGender.classes[0].students[0].nameTag, '', 'legacy students keep a blank tag')
const tagRows = recognizeRows(parseDelimited('班级,姓名,重名标识,性别,分数\n高一1班,王明,甲,男,8\n高一1班,王明,乙,女,3\n高一2班,王明,甲,男,6'), initial.name)
const tagged = importCandidates(store, tagRows).store
assert.equal(tagged.classes[0].students.length, 2, 'same class/name with distinct tags must be separate students')
assert.notEqual(studentIdentity(initial.id, tagged.classes[0].students[0]), studentIdentity(initial.id, tagged.classes[0].students[1]))
assert.equal(studentLabel(tagged.classes[0].students[1]), '王明（乙）')
const taggedBound = bindStudentRole(tagged, initial.id, tagged.classes[0].students[0].id, '男', avatar)
assert.throws(() => bindStudentRole(taggedBound, initial.id, tagged.classes[0].students[1].id, '女', avatar), /同班不能重复/, 'same-name students still cannot share custom roles')
const tagUpdated = importCandidates(taggedBound, [{ ...tagRows[1], score: 15 }], true).store
assert.equal(tagUpdated.classes[0].students[0].score, 8)
assert.equal(tagUpdated.classes[0].students[0].avatar, avatar)
assert.equal(tagUpdated.classes[0].students[1].score, 15)
assert.equal(tagUpdated.classes[1].students[0].score, 6)
assert.equal(importCandidates(tagged, tagRows).skipped, 3, 'duplicate protection must use all three identity fields')
assert.throws(() => updateStudentNameTag(taggedBound, initial.id, tagged.classes[0].students[0].id, '乙'), /已有相同/)
assert.throws(() => updateStudentNameTag(taggedBound, initial.id, tagged.classes[0].students[0].id, '三个字'), /最多2个字/)
const renamedTag = updateStudentNameTag(taggedBound, initial.id, tagged.classes[0].students[0].id, ' 新甲 ')
assert.deepEqual(renamedTag.classes[0].students[0], { ...taggedBound.classes[0].students[0], nameTag: '新甲' }, 'tag edits preserve every other field including id/image/route/mottos')
assert.equal(recognizeRows([['姓名', '重名标识', '性别'], ['王明', '三个字', '男']], initial.name)[0].error, '重名标识最多2个字')
assert.throws(() => importCandidates(store, [{ ...tagRows[0], nameTag: '三个字' }]), /最多2个字/)
const taggedClear = clearClassroomRoster(taggedBound, initial.id)
const sameNameNewTag = importCandidates(taggedClear.store, [{ ...tagRows[0], nameTag: '丙' }]).store
assert.equal(restoreClassroomRoster(sameNameNewTag, taggedClear.snapshot).classes[0].students.length, 3, 'undo must retain same names with different tags')
const tagRoundtripBlob = await exportClassrooms(taggedBound.classes)
const tagRoundtrip = new ExcelJS.Workbook()
await tagRoundtrip.xlsx.load(await tagRoundtripBlob.arrayBuffer())
assert.equal(tagRoundtrip.worksheets[1].getCell('J1').value, '重名标识')
assert.equal(tagRoundtrip.worksheets[1].getCell('J2').value, '甲')
const tagNoPhotos = await exportClassrooms(tagged.classes)
const tagParsed = await readExcelCandidates(new File([tagNoPhotos], 'tag-roundtrip.xlsx'), initial.name)
assert.deepEqual(tagParsed.map(row => [row.className, row.name, row.nameTag]), tagRows.map(row => [row.className, row.name, row.nameTag]))
assert.equal(importCandidates(tagged, tagParsed).skipped, 3)
const collisionRestore = restoreClassroomRoster(importCandidates(clearClassroomRoster(bound, initial.id).store, [{ ...candidates[0], name: '新增角色主人', avatar }]).store, clearClassroomRoster(bound, initial.id).snapshot)
assert.equal(collisionRestore.classes[0].students.filter(student => student.avatar === avatar).length, 1, 'undo must not assign an occupied custom role twice')
const exported = await exportClassrooms(imported.store.classes, avatar, avatar)
const workbook = new ExcelJS.Workbook()
await workbook.xlsx.load(await exported.arrayBuffer())
assert.equal(workbook.worksheets.length, 3, 'all-class export has a summary and one sheet per class')
assert.equal(workbook.worksheets[1].getCell('A2').value, '高一1班')
assert.equal(workbook.worksheets[1].getCell('D2').value, 7)
assert.equal(workbook.worksheets[1].getCell('H2').value, '男')
assert.equal(workbook.worksheets[1].getCell('I2').value, '默认角色')
assert.equal(workbook.worksheets[1].getImages().length, 2, 'avatars must be embedded, not URLs')
assert.ok(workbook.getImage(Number(workbook.worksheets[1].getImages()[0].imageId)).buffer.byteLength > 0)
const withoutPhotos = await exportClassrooms(imported.store.classes)
const parsed = await readExcelCandidates(new File([withoutPhotos], 'roundtrip.xlsx'), '默认班级')
assert.equal(parsed.length, 3)
assert.ok(parsed.some(row => row.className === '高一1班' && row.name === '张,三' && row.score === 7))
assert.ok(parsed.some(row => row.name === '李四' && row.gender === '女'))
const template = new ExcelJS.Workbook()
const templateBuffer = readFileSync(new URL('../public/templates/leaderboard-import-template.xlsx', import.meta.url))
await template.xlsx.load(await normalizeExcelArchive(templateBuffer.buffer.slice(templateBuffer.byteOffset, templateBuffer.byteOffset + templateBuffer.byteLength)))
assert.deepEqual(template.worksheets[0].getRow(1).values.slice(1, 5), ['班级', '姓名', '图片', '分数'])
assert.equal(template.worksheets[0].getImages().length, 1)
assert.equal(template.worksheets[0].getCell('D2').value, 0)
assert.equal(template.worksheets[0].getCell('H1').value, '性别')
assert.equal(template.worksheets[0].getCell('H3').value, '女')
assert.equal(template.worksheets[0].getCell('I1').value, '重名标识')
const profileCandidates = recognizeRows(parseDelimited('班级,姓名,性别,性格,爱好\n高一1班,小雨,女,细心,"阅读、画画\n旅行"'), initial.name)
const profileStore = importCandidates(store, profileCandidates).store
const profileStudent = profileStore.classes[0].students[0]
assert.equal(profileStudent.personality, '细心')
assert.equal(profileStudent.hobbies, '阅读、画画\n旅行')
const legacyProfile = recognizeRows([['班级', '姓名', '性别', '分数'], ['高一1班', '小雨', '女', '8']], initial.name)
const profilePreserved = importCandidates(profileStore, legacyProfile, true).store.classes[0].students[0]
assert.equal(profilePreserved.score, 8)
assert.equal(profilePreserved.personality, '细心', 'old files lacking columns must preserve profile values even in overwrite mode')
assert.equal(profilePreserved.hobbies, profileStudent.hobbies)
const blankProfile = recognizeRows([['姓名', '性别', '性格', '爱好'], ['小雨', '女', '', '']], initial.name)
assert.equal(importCandidates(profileStore, blankProfile).store.classes[0].students[0].personality, '细心', 'unchecked overwrite preserves all existing profile values')
assert.equal(importCandidates(profileStore, blankProfile, true).store.classes[0].students[0].personality, '', 'explicit blank columns can clear profile values')
assert.equal(importCandidates(profileStore, blankProfile, true).store.classes[0].students[0].hobbies, '')
assert.match(recognizeRows([['姓名', '性别', '性格'], ['小雨', '女', '长'.repeat(121)]], initial.name)[0].error, /120/)
assert.throws(() => importCandidates(profileStore, [{ ...profileCandidates[0], hobbies: '长'.repeat(121) }], true), /120/)
const oldRoster = loadClassrooms({ getItem: () => JSON.stringify(imported.store) }, [], 50)
assert.equal(oldRoster.classes[0].students[0].personality, '')
assert.equal(oldRoster.classes[0].students[0].hobbies, '')
const profileExport = await exportClassrooms(profileStore.classes)
const profileImported = await readExcelCandidates(new File([profileExport], 'profile-roundtrip.xlsx'), initial.name)
assert.equal(profileImported[0].personality, profileStudent.personality)
assert.equal(profileImported[0].hobbies, profileStudent.hobbies)
const previousFetch = globalThis.fetch
globalThis.fetch = async () => new Response(templateBuffer)
try {
  const updatedTemplate = new ExcelJS.Workbook()
  await updatedTemplate.xlsx.load(await (await createImportTemplate()).arrayBuffer())
  assert.equal(updatedTemplate.worksheets[0].getCell('J1').value, '性格')
  assert.equal(updatedTemplate.worksheets[0].getCell('K1').value, '爱好')
  assert.equal(updatedTemplate.worksheets[0].getImages().length, 1, 'new template preserves its existing embedded image')
} finally { globalThis.fetch = previousFetch }
console.log('PASS: class isolation, statistics, CSV quoting, zero defaults, preview validation, duplicate protection, route allocation/persistence, XLSX round-trip, embedded images and downloadable template.')
